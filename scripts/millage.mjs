// Builds public/millage-2026.js from the Property Appraiser's 2026 adopted millage chart.
// Source rows: scripts/data/millage/2026-adopted-rows.txt, one line per area, values in the chart's
// printed order: city operating, city debt (if any), School Board (state + local 5.4990, voted 1.0000,
// debt 0.1240), regional (SFWMD 0.0948, Everglades 0.0327, Okeechobee 0.1026, FIND 0.0270),
// County-wide 4.5740, County debt 0.3937, Fire Rescue 2.3965 and Library 0.2812 where the County
// provides them, Children's Trust 0.4638, then the printed total. Rows for sub-areas (Miami DDA,
// Normandy Shores) are left out: the page can't tell from a lookup whether a home is in one.
// Run: node scripts/millage.mjs
import fs from 'node:fs';

export const SOURCE = { name: 'Miami-Dade Property Appraiser, 2026 adopted millage rates', url: 'https://www.miamidadepa.gov/resources-pa/library/reports/millage/2026-adopted-millage-chart.pdf' };
export const SHARED = { schoolOps: 5.499, schoolVoted: 1.0, schoolDebt: 0.124, regional: 0.0948 + 0.0327 + 0.1026, find: 0.027, county: 4.574, countyDebt: 0.3937, fire: 2.3965, library: 0.2812, trust: 0.4638 };
const r4 = x => Math.round(x * 1e4) / 1e4;

export function build(text) {
  const places = {};
  for (const line of text.split('\n').map(l => l.trim()).filter(Boolean)) {
    const [name, vals] = line.split('|');
    const v = vals.trim().split(/\s+/).map(Number);
    const total = v.pop();
    const sum = r4(v.reduce((a, b) => a + b, 0));
    if (Math.abs(sum - total) > 0.00005) throw new Error(name + ': parts add to ' + sum + ', chart says ' + total);
    if (/\(/.test(name)) continue;
    const i = v.indexOf(SHARED.schoolOps);
    if (i < 1) throw new Error(name + ': no city rate before the School Board rate');
    const tail = v.slice(i);
    places[name] = { city: v[0], cityDebt: r4(v.slice(1, i).reduce((a, b) => a + b, 0)), fire: tail.includes(SHARED.fire), library: tail.includes(SHARED.library), total };
  }
  return { year: 2026, source: SOURCE, shared: SHARED, places };
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const data = build(fs.readFileSync(new URL('./data/millage/2026-adopted-rows.txt', import.meta.url), 'utf8'));
  fs.writeFileSync(new URL('../public/millage-2026.js', import.meta.url),
    '// Generated by scripts/millage.mjs from the Property Appraiser\'s 2026 adopted millage chart. Do not edit.\nwindow.MILLAGE_2026 = ' + JSON.stringify(data, null, 1) + ';\n');
  console.log(Object.keys(data.places).length + ' places');
}
