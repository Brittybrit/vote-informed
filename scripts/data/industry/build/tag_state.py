R=[(re.compile(p),t) for p,t in R]
def tag(name,v):
    occ=' / '.join(v['occs'])
    s=name+' || '+occ
    tags=[]
    for rx,t in R:
        target=occ if t==["individual-noindustry"] else s
        if t==["individual-noindustry"]:
            if all(rx.search(o.strip()) for o in v['occs'] if o.strip()) and not tags: tags+= t
            continue
        if rx.search(s):
            for x in t:
                if x not in tags: tags.append(x)
    def drop(x,cond):
        if cond and x in tags: tags.remove(x)
    drop('insurance-other','insurance-health' in tags or 'insurance-property' in tags)
    drop('health-other','insurance-health' in tags)
    drop('securities-investment', 'realestate-dev' in tags and re.search(r'REAL ESTATE INVEST|R\.E\. INVEST|REAL ESTATE INVESTOR|INVESTMENT CO',s))
    drop('trade-association','labor-union' in tags)
    drop('trade-association',re.search(r'ASSOCIATIONS, INC|MANAGEMENT ASSOCIATION|DORSEY & ASSOCIATION',name))
    drop('pharma','pharmacies-pbm' in tags)
    drop('law-firm',re.search(r'MERCK',name))
    drop('lobbying',re.search(r'UNIVERSAL CITY',name))
    drop('health-other','hospitals' in tags or 'nursing-homes' in tags)
    drop('other','banks' in tags)
    if 'labor-union' in tags:
        tags[:]=[x for x in tags if x in ('labor-union','political-committee')]
    if re.search(r'^PC BUILDING',name): drop('political-committee',True)
    drop('construction',re.search(r'TRAFFIC',s))
    drop('law-firm',re.search(r'TITLE INSURANCE THROUGH',name) is None and 'insurance-other' in tags and re.search(r'ATTORNEYS TITLE',name))
    return tags
